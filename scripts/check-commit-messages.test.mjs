import assert from "node:assert/strict";
import { execFileSync } from "node:child_process";
import { mkdtempSync, rmSync, writeFileSync } from "node:fs";
import { tmpdir } from "node:os";
import { join } from "node:path";
import test from "node:test";
import { check, findTrailers } from "./check-commit-messages.mjs";

const flagged = [
  "Fix the footer\n\nCo-Authored-By: Claude Opus 5.5 <noreply@anthropic.com>",
  "Fix\n\nCo-authored-by: Claude <claude@users.noreply.github.com>",
  "Fix\n\nCo-Authored-By: Codex <codex@openai.com>",
  "Fix\n\nCo-Authored-By: Codebuff <noreply@codebuff.com>",
  "Fix\n\nCo-Authored-By: GitHub Copilot <copilot@github.com>",
  "Fix\n\nCo-Authored-By: Some Bot <bot@anthropic.com>",
  "Fix\n\n🤖 Generated with [Claude Code](https://claude.com/claude-code)",
  "Fix\n\nGenerated with Codebuff",
  "Fix\n\ngenerated WITH an assistant",
  "Fix\n\nGenerated by Claude",
  "Fix\n\n🤖 reviewed",
];
const clean = [
  "Fix the footer",
  "Fix the footer\n\nCo-Authored-By: Ada Lovelace <ada@example.com>",
  "Add a page generator\n\nThe script builds the pages from the copy in the repository.",
  "Write the claude-code docs\n\nMentions the Claude model name in prose only.",
  "Merge the cursor fix\n\nThe cursor no longer jumps.",
];

test("flags AI attribution trailers", () => {
  for (const message of flagged) assert.ok(findTrailers(message).length > 0, message);
});
test("passes ordinary messages, human co-authors and prose that only mentions a tool", () => {
  for (const message of clean) assert.deepEqual(findTrailers(message), [], message);
});
test("reports the offending line", () => {
  const [f] = findTrailers("Fix\n\nBody\nCo-Authored-By: Claude <noreply@anthropic.com>");
  assert.match(f.line, /^Co-Authored-By: Claude/);
});
test("checks every commit in base..head of a real repository", () => {
  const dir = mkdtempSync(join(tmpdir(), "msgcheck-"));
  try {
    const git = (...args) => execFileSync("git", args, { cwd: dir, encoding: "utf8" }).trim();
    git("init", "-q", "-b", "main");
    git("config", "user.email", "t@example.com"); git("config", "user.name", "T"); git("config", "commit.gpgsign", "false");
    const commit = (message) => { writeFileSync(join(dir, "f"), message); git("add", "f"); git("commit", "-q", "-m", message); return git("rev-parse", "HEAD"); };
    const base = commit("base commit\n\nCo-Authored-By: Claude <noreply@anthropic.com>");
    commit("clean change");
    const bad = commit("second change\n\nCo-Authored-By: Claude <noreply@anthropic.com>");
    commit("third change\n\n🤖 Generated with [Claude Code](https://claude.com/claude-code)");
    const result = check(base, "HEAD", dir);
    assert.equal(result.length, 2, "the base commit is outside base..head; the clean one passes");
    assert.equal(result[1].sha, bad);
    assert.deepEqual(check("HEAD", "HEAD", dir), []);
  } finally { rmSync(dir, { recursive: true, force: true }); }
});
